/** Shipped bundle-depth metadata (static fallback).
 *
 *  The engine keeps per-bundle depth as data files under its (gitignored) data
 *  dir, so a hosted engine that never stored a bundle answers 404 on
 *  /api/bundles/{id}. When that route is unavailable, useBundle serves this
 *  shipped registry instead — the same presence-only numbers the engine route
 *  would return (GUNW pairs/dates stored, GCOV epochs, cold start, flags).
 *  Data only, verbatim from the verdict store: no science is computed here. */

export interface BundleDepth {
  n_gunw_pairs: number | null;
  n_gunw_dates: number | null;
  n_gcov_epochs: number | null;
  cold_start: boolean | null;
}

export interface BundleInfo {
  bundle_id: string;
  tile: Record<string, unknown>;
  epoch: string | null;
  status: string | null;
  depth: BundleDepth;
  routing_decisions: unknown;
  applicable: unknown;
  flags: string[];
}

